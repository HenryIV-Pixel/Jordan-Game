"""Generate src/data/mapData.ts from Natural Earth vector data (public domain).

Usage:  python3 tools/build_map_data.py /path/to/natural-earth-vector/geojson

Produces SVG path strings in a fixed 872 x 756 projected frame (equirectangular,
scaled by cos(latitude)) covering Jordan in its 1950-1967 borders and its
neighbours, plus the projection constants so the game can place towns.
"""
import json, math, sys
from shapely.geometry import shape, box
from shapely.ops import unary_union
from shapely.affinity import affine_transform

NE = sys.argv[1].rstrip("/") + "/"
OUT = "src/data/mapData.ts"

W, H = 872, 756
LON0, LAT1, LAT0 = 33.6, 33.55, 28.95
KY = H / (LAT1 - LAT0)
KX = KY * math.cos(math.radians((LAT1 + LAT0) / 2))
BBOX = box(LON0 - 0.3, LAT0 - 0.3, LON0 + W / KX + 0.3, LAT1 + 0.3)


def proj(g):
    return affine_transform(g, [KX, 0, 0, -KY, -KX * LON0, KY * LAT1])


def d_of(geom, tol=0.35):
    g = proj(geom).simplify(tol, preserve_topology=True)
    parts = []

    def ring(cs, close):
        pts = [f"{x:.1f} {y:.1f}" for x, y in cs]
        if len(pts) >= 2:
            parts.append("M" + "L".join(pts) + ("Z" if close else ""))

    def walk(gg):
        t = gg.geom_type
        if t == "Polygon":
            ring(gg.exterior.coords, True)
            for i in gg.interiors:
                ring(i.coords, True)
        elif t == "LineString":
            ring(gg.coords, False)
        elif hasattr(gg, "geoms"):
            for s in gg.geoms:
                walk(s)
    walk(g)
    return "".join(parts)


def load(n):
    return json.load(open(NE + n))["features"]


def clip(g):
    return g.intersection(BBOX) if g.intersects(BBOX) else None


countries = {f["properties"]["ADM0_A3"]: shape(f["geometry"]) for f in load("ne_10m_admin_0_countries.geojson")
             if shape(f["geometry"]).intersects(BBOX)}
a1 = [f for f in load("ne_10m_admin_1_states_provinces.geojson") if f["properties"].get("adm0_a3") in ("JOR", "PSX")]
wb = next(shape(f["geometry"]) for f in a1 if f["properties"]["name"] == "West Bank")
jordan = countries["JOR"]
# 1953: the Golan belongs to Syria, not Israel.
golan = box(35.62, 32.6, 36.6, 33.5)
if "ISR" in countries:
    g = countries["ISR"].intersection(golan)
    countries["ISR"] = countries["ISR"].difference(golan)
    if "SYR" in countries:
        countries["SYR"] = countries["SYR"].union(g)

NAMES_AR = {"SYR": "سوريا", "IRQ": "العراق", "SAU": "السعودية", "ISR": "إسرائيل", "EGY": "مصر", "LBN": "لبنان", "PSX": ""}
neighbours = []
for code, g in countries.items():
    if code == "JOR":
        continue
    c = clip(g.difference(wb)) if code == "PSX" else clip(g)
    if c is None or c.is_empty:
        continue
    neighbours.append({"id": code, "name": NAMES_AR.get(code, ""), "d": d_of(c)})

GOV_AR = {"Irbid": "إربد", "Madaba": "مادبا", "Karak": "الكرك", "Tafilah": "الطفيلة", "Aqaba": "العقبة", "Balqa": "البلقاء",
          "Mafraq": "المفرق", "Ma`an": "معان", "Amman": "عمّان", "Zarqa": "الزرقاء", "Ajlun": "عجلون", "Jarash": "جرش"}
districts = []
for f in a1:
    p = f["properties"]
    if p["adm0_a3"] != "JOR":
        continue
    districts.append({"id": p["name"].lower().replace("`", ""), "name": GOV_AR.get(p["name"], p["name"]), "d": d_of(shape(f["geometry"]))})

inner = unary_union([shape(f["geometry"]).boundary for f in a1 if f["properties"]["adm0_a3"] == "JOR"]).difference(jordan.boundary.buffer(0.01))
kingdom = unary_union([jordan, wb])

water_sea = [d_of(c) for c in (clip(shape(f["geometry"])) for f in load("ne_10m_ocean.geojson")) if c is not None]
lakes = [d_of(c, 0.2) for c in (clip(shape(f["geometry"])) for f in load("ne_10m_lakes.geojson")) if c is not None]
rivers = [d_of(c, 0.3) for c in (clip(shape(f["geometry"])) for f in load("ne_10m_rivers_lake_centerlines.geojson")) if c is not None]
roads = []
for f in load("ne_10m_roads.geojson"):
    if f["properties"].get("type") not in ("Major Highway", "Secondary Highway", "Road"):
        continue
    c = clip(shape(f["geometry"]))
    if c is not None:
        roads.append(d_of(c, 0.6))
rail = [d_of(c, 0.4) for c in (clip(shape(f["geometry"])) for f in load("ne_10m_railroads.geojson")) if c is not None]

data = {
    "width": W, "height": H, "lon0": LON0, "lat1": LAT1, "kx": KX, "ky": KY,
    "neighbours": neighbours,
    "eastBank": d_of(clip(jordan)),
    "westBank": d_of(clip(wb)),
    "kingdomBorder": d_of(clip(kingdom)),
    "districts": districts,
    "districtLines": d_of(clip(inner), 0.5),
    "sea": water_sea, "lakes": lakes, "rivers": rivers, "roads": roads, "rail": rail,
}
with open(OUT, "w") as fh:
    fh.write("// Generated by tools/build_map_data.py from Natural Earth (public domain). Do not edit by hand.\n")
    fh.write("export const MAP = " + json.dumps(data, ensure_ascii=False) + " as const;\n")
print("wrote", OUT, sum(len(v) if isinstance(v, str) else 0 for v in data.values()))
